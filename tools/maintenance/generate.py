from common import ROOT, fresh_output, source_file


def integer(expression, names):
    expression = re.sub(r'\b(0[xX][0-9a-fA-F]+|[0-9]+)[uUlL]+\b', r'\1', expression)
    if len(expression) > 256:
        raise ValueError('constant expression too long')
    tree = ast.parse(expression, mode='eval')

    def visit(node):
        if isinstance(node, ast.Constant) and type(node.value) is int:
            value = node.value
        elif isinstance(node, ast.Name) and node.id in names:
            value = names[node.id]
        elif isinstance(node, ast.BinOp) and isinstance(node.op, (ast.LShift, ast.BitOr, ast.Sub, ast.Add)):
            left, right = visit(node.left), visit(node.right)
            if isinstance(node.op, ast.LShift):
                if not 0 <= right <= 63:
                    raise ValueError('invalid constant shift')
                value = left << right
            elif isinstance(node.op, ast.BitOr):
                value = left | right
            elif isinstance(node.op, ast.Sub):
                value = left - right
            else:
                value = left + right
        else:
            raise ValueError(f'unsupported constant expression: {expression}')
        if type(value) is not int or not 0 <= value < 2**64:
            raise ValueError('constant outside unsigned 64-bit range')
        return value
    return visit(tree.body)


def constants(header):
    values = {}
    aliases = {'FvwmPacketHeaderSize': 'HEADER_SIZE',
               'ModuleFinishedStartupResponse': 'RESPONSE_READY',
               'ModuleUnlockResponse': 'RESPONSE_UNLOCK'}
    for name, expression in re.findall(r'^#define\s+(\w+)\s+([^\n]+)', header, re.M):
        if not (name.startswith(('M_', 'MX_')) or name in aliases or
                name in ('MAX_MSG_MASK', 'MAX_XMSG_MASK', 'START_FLAG')):
            continue
        if name in values:
            raise ValueError(f'duplicate definition: {name}')
        expression = expression.split('/*', 1)[0].strip()
        value = json.loads(expression) if expression.startswith('"') else integer(expression, values)
        values[name] = value
    required = {'M_EXTENDED_MSG', 'MX_REPLY', 'FvwmPacketHeaderSize',
                'ModuleUnlockResponse', 'ModuleFinishedStartupResponse'}
    if not required <= values.keys():
        raise ValueError('required protocol definitions missing')
    return {aliases.get(name, name): value for name, value in values.items()}


def perl_string(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def perl_constants(values):
    lines = [generated_notice(), 'package FVWM::Constants;',
             'use strict;', 'use warnings;', 'use Exporter;', 'use Config;',
             'our @ISA = qw(Exporter);']
    for name, value in values.items():
        encoded = perl_string(value) if isinstance(value, str) else str(value)
        lines.append(f'use constant {name} => {encoded};')
    lines += ["use constant ON_EXIT => '1e20';", 'use constant INTSIZE => $Config{longsize};',
              'our @EXPORT = qw(\n' + '\n'.join('  ' + name for name in
                  list(values) + ['ON_EXIT', 'INTSIZE']) + '\n);', '1;',
              '__END__', metadata_pod('Constants'), '=head1 EXPORTED CONSTANTS', '',
              '\n'.join('  ' + name for name in list(values) + ['ON_EXIT', 'INTSIZE'])]
    return '\n'.join(lines) + '\n'


def generated_notice():
    return ('# Generated by tools/maintenance/generate.py metadata; do not edit.\n'
            '# This program is free software; you can redistribute it and/or modify\n'
            '# it under the terms of the GNU General Public License as published by\n'
            '# the Free Software Foundation; either version 2, or any later version.')


def metadata_pod(name):
    return (Path(__file__).parent / 'metadata' / (name + '.pod')).read_text().strip()


def commands(text):
    table = text.split('const func_t func_table[] =', 1)[1]
    pattern = re.compile(r'CMD_ENT\(\s*("[^"]+"|PRE_[A-Z_]+)\s*,\s*CMD_(\w+)\s*,\s*\w+\s*,\s*([\w\s|]+?)\s*,\s*(\w+)\s*\),\s*(?:\*/)?\s*/\*\s*(.*?)\s*\*/', re.S)
    matches = list(pattern.finditer(table))
    if not matches or len(matches) != table.count('CMD_ENT('):
        raise ValueError('command table format changed; refusing incomplete generation')
    result = []
    for match in matches:
        spelling, function, flags, cursor, comment = match.groups()
        label, separator, description = comment.partition(' - ')
        if not separator:
            if comment.startswith('- '):
                label, description = '', comment[2:]
            else:
                raise ValueError(f'command description missing: {spelling}')
        result.append({'name': label.strip() or function,
                       'cursor': cursor.removeprefix('CRS_') if cursor != '0' else '',
                       'window': int('FUNC_NEEDS_WINDOW' in flags.split()),
                       'descr': description.strip()})
    return result


def metadata(source, output, epoch):
    values = constants(source_file(source, 'libs/Module.h').read_text())
    marker = values['M_EXTENDED_MSG']
    extended = [value for name, value in values.items()
                if name.startswith('MX_') and value & marker]
    mask = 0
    for value in extended:
        bits = value & ~marker
        if bits == 0 or bits & (bits - 1) or bits & mask:
            raise ValueError('extended event must have one unique bit')
        mask |= bits
    if mask != values['MAX_XMSG_MASK']:
        raise ValueError('MAX_XMSG_MASK must cover exactly the named events')
    entries = commands(source_file(source, 'fvwm/functable.c').read_text())
    version = source_file(source, '.current-version').read_text().strip()
    with fresh_output(output, source) as stage:
        (stage / 'Constants.pm').write_text(perl_constants(values))
        lines = [generated_notice(),
                 'package FVWM::Commands;', 'use strict;', 'use warnings;',
                 'our ($VERS, $TIME, @LIST);',
                 '$VERS = ' + perl_string(version) + ';', f'$TIME = {epoch};', '@LIST = (']
        for entry in entries:
            parts = [key + ' => ' + (str(value) if isinstance(value, int) else perl_string(value))
                     for key, value in entry.items()]
            lines.append('    {' + ', '.join(parts) + '},')
        lines += [');', '1;', '__END__', metadata_pod('Commands')]
        (stage / 'Commands.pm').write_text('\n'.join(lines) + '\n')
        (stage / 'protocol.json').write_text(json.dumps(values, indent=2) + '\n')
        (stage / 'commands.json').write_text(json.dumps(entries, indent=2) + '\n')
        inputs = {name: hashlib.sha256(source_file(source, name).read_bytes()).hexdigest()
                  for name in ('libs/Module.h', 'fvwm/functable.c', '.current-version')}
        for name in ('Constants', 'Commands'):
            path = Path(__file__).parent / 'metadata' / (name + '.pod')
            inputs['tools/maintenance/metadata/' + name + '.pod'] = hashlib.sha256(path.read_bytes()).hexdigest()
        inputs['tools/maintenance/generate.py'] = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
        (stage / 'metadata-inputs.json').write_text(json.dumps(
            {'epoch': epoch, 'input_sha256': inputs}, indent=2) + '\n')


def parsers(source, output, bison, flex, expected_bison, expected_flex):
    versions = {}
    for program, expected in ((bison, expected_bison), (flex, expected_flex)):
        line = subprocess.check_output([program, '--version'], text=True).splitlines()[0]
        found = re.search(r'\b\d+\.\d+(?:\.\d+)?\b', line)
        if not found or found.group() != expected:
            raise ValueError(f'generator version mismatch: {line}; expected {expected}')
        versions[program] = line
    with fresh_output(output, source) as stage:
        for name in ('script.y', 'scanner.l'):
            (stage / name).write_bytes(source_file(source, 'modules/FvwmScript/' + name).read_bytes())
        # Stable relative input/output names keep temporary paths out of #line.
        subprocess.run([bison, '-y', '--defines=script.h', '--output=script.c', 'script.y'], cwd=stage, check=True)
        subprocess.run([flex, '--nounput', '--outfile=scanner.c', 'scanner.l'], cwd=stage, check=True)
        for name in ('script.c', 'script.h', 'scanner.c'):
            if not (stage / name).is_file():
                raise ValueError(f'generator produced no {name}')
        for name in ('script.c', 'scanner.c'):
            includes = re.findall(r'^\s*#\s*include\s*([<"][^>"\n]+[>"])',
                                  (stage / name).read_text(), re.M)
            if not includes or includes[0] != '"config.h"':
                raise ValueError(f'{name} must include config.h first')
        versions['input_sha256'] = {
            name: hashlib.sha256((stage / name).read_bytes()).hexdigest()
            for name in ('script.y', 'scanner.l')
        }
        versions['output_sha256'] = {
            name: hashlib.sha256((stage / name).read_bytes()).hexdigest()
            for name in ('script.c', 'script.h', 'scanner.c')
        }
        (stage / 'generators.json').write_text(json.dumps(versions, indent=2) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('kind', choices=['metadata', 'parsers'])
    parser.add_argument('--source', type=Path, default=ROOT)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--epoch', type=int, default=0)
    parser.add_argument('--bison', default='bison')
    parser.add_argument('--flex', default='flex')
    parser.add_argument('--bison-version', default='3.8.2')
    parser.add_argument('--flex-version', default='2.6.4')
    args = parser.parse_args()
    if args.epoch < 0:
        parser.error('--epoch must be nonnegative')
    if args.kind == 'metadata':
        metadata(args.source, args.output, args.epoch)
    else:
        parsers(args.source, args.output, args.bison, args.flex,
                args.bison_version, args.flex_version)


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, SyntaxError, IndexError, subprocess.CalledProcessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
